#!/bin/sh
# Downloads the current Cloudflare IP ranges and writes the two nginx snippets used by
# splitto.conf, then reloads nginx. Run once at setup and then monthly (cron):
#   sudo /opt/splitto/produzione/nginx/aggiorna-ip-cloudflare.sh
set -eu

DIR=/etc/nginx/snippets
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# The lists have no trailing newline: add one, so v4 and v6 never end up on the same line.
{ curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4; echo; } > "$TMP/v4"
{ curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6; echo; } > "$TMP/v6"
# Refuse to continue on an empty or odd answer (never lock everyone out).
[ "$(grep -c '/' "$TMP/v4")" -ge 10 ] || { echo "Lista IPv4 di Cloudflare non valida" >&2; exit 1; }

{
	echo "# Generated by aggiorna-ip-cloudflare.sh on $(date -u +%F) — do not edit."
	echo "# Trust Cloudflare's header for the real visitor IP, only from Cloudflare addresses."
	cat "$TMP/v4" "$TMP/v6" | sed '/^$/d; s/^/set_real_ip_from /; s/$/;/'
	echo "real_ip_header CF-Connecting-IP;"
} > "$TMP/cloudflare-realip.conf"

{
	echo "# Generated by aggiorna-ip-cloudflare.sh on $(date -u +%F) — do not edit."
	echo "# Used by: geo \$realip_remote_addr \$from_cloudflare { ... }"
	cat "$TMP/v4" "$TMP/v6" | sed '/^$/d; s/$/ 1;/'
} > "$TMP/cloudflare-allow.conf"

# Replace the snippets, but restore the previous ones if nginx rejects the new files.
mkdir -p "$DIR"
for f in cloudflare-realip.conf cloudflare-allow.conf; do
	[ -f "$DIR/$f" ] && cp "$DIR/$f" "$TMP/$f.bak"
	cp "$TMP/$f" "$DIR/$f"
done
if nginx -t; then
	systemctl reload nginx
	echo "IP di Cloudflare aggiornati in $DIR"
else
	for f in cloudflare-realip.conf cloudflare-allow.conf; do
		[ -f "$TMP/$f.bak" ] && cp "$TMP/$f.bak" "$DIR/$f"
	done
	echo "nginx -t fallito: ripristinati gli snippet precedenti" >&2
	exit 1
fi
